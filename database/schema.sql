CREATE TABLE IF NOT EXISTS cliente (
    id_cliente INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome VARCHAR(100) NOT NULL,
    telefone VARCHAR(20) NOT NULL
);

CREATE TABLE IF NOT EXISTS funcionario (
    id_funcionario INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome VARCHAR(100) NOT NULL,
    funcao VARCHAR(50) NOT NULL
);

CREATE TABLE IF NOT EXISTS equipamento (
    id_equipamento INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    descricao VARCHAR(255) NOT NULL,
    tipo VARCHAR(50) NOT NULL,
    id_cliente INTEGER NOT NULL REFERENCES cliente(id_cliente)
);

CREATE TABLE IF NOT EXISTS ordem_servico (
    id_os INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    data_abertura DATE NOT NULL DEFAULT CURRENT_DATE,
    status VARCHAR(30) NOT NULL,
    id_cliente INTEGER NOT NULL REFERENCES cliente(id_cliente),
    id_equipamento INTEGER NOT NULL REFERENCES equipamento(id_equipamento),
    id_funcionario INTEGER NOT NULL REFERENCES funcionario(id_funcionario)
);

CREATE TABLE IF NOT EXISTS manutencao (
    id_manutencao INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    descricao TEXT NOT NULL,
    data_manutencao DATE NOT NULL,
    id_os INTEGER NOT NULL REFERENCES ordem_servico(id_os)
);
